def update_sandbox(sandbox_slug, new_modules):
    sandbox_dir = ROOT / sandbox_slug
    tests_dir = sandbox_dir / "data" / "tests"
    tests_dir.mkdir(parents=True, exist_ok=True)
    
    # 1. Write the 4 new test JSON files (without touching existing 80 files!)
    for mod in new_modules:
        tid = mod["test_id"]
        t_path = tests_dir / f"{tid}.json"
        with open(t_path, "w", encoding="utf-8") as f:
            json.dump(mod, f, indent=2, ensure_ascii=False)
        print(f"  [OK] Wrote specialized test: {tid}.json ({mod['title'][:50]}...)")

    # 2. Update curriculum_manifest.json (append new modules without deleting existing ones!)
    manifest_path = sandbox_dir / "data" / "curriculum_manifest.json"
    with open(manifest_path, "r", encoding="utf-8") as f:
        existing_curr = json.load(f)
    
    existing_tids = {m["test_id"] for m in existing_curr}
    for mod in new_modules:
        if mod["test_id"] not in existing_tids:
            curr_entry = {
                "test_id": mod["test_id"],
                "title": mod["title"],
                "level": mod["level"],
                "category": mod["category"],
                "workplace_track": mod["workplace_track"],
                "grammar_focus": mod["grammar_focus"],
                "estimated_time_minutes": mod["estimated_time_minutes"],
                "description": mod["description"]
            }
            existing_curr.append(curr_entry)
            existing_tids.add(mod["test_id"])

    with open(manifest_path, "w", encoding="utf-8") as f:
        json.dump(existing_curr, f, indent=2, ensure_ascii=False)
    print(f"  [OK] curriculum_manifest.json now has {len(existing_curr)} total modules")

    # 3. Update manifest.js
    manifest_js_path = sandbox_dir / "data" / "manifest.js"
    with open(manifest_js_path, "w", encoding="utf-8") as f:
        f.write("window.CURRICULUM_MANIFEST = " + json.dumps(existing_curr, indent=2, ensure_ascii=False) + ";\n")
    print(f"  [OK] manifest.js updated")

    # 4. Update tests_registry.js (merge new modules with existing ones!)
    # Read existing registry by loading all tests in tests_dir
    all_tests_map = {}
    for jf in sorted(tests_dir.glob("*.json")):
        with open(jf, "r", encoding="utf-8") as f:
            all_tests_map[jf.stem] = json.load(f)

    reg_js_path = sandbox_dir / "data" / "tests_registry.js"
    with open(reg_js_path, "w", encoding="utf-8") as f:
        f.write("window.TEST_REGISTRY = window.TEST_REGISTRY || {};\n")
        f.write("Object.assign(window.TEST_REGISTRY, " + json.dumps(all_tests_map, indent=2, ensure_ascii=False) + ");\n")
    print(f"  [OK] tests_registry.js updated with {len(all_tests_map)} total bundled tests")


